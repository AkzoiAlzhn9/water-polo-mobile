WP.hash = function (s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return (h >>> 0) / 4294967295;
};

// Атрибуты 0..100 из рейтинга команды, амплуа и детерминированного разброса
WP.makeAttrs = function (team, p, ratingShift) {
  const [, name, role, star] = p;
  // −4: чтобы у лучших сборных параметры не упирались в потолок 99 и игроки различались
  const base = team.rating + (ratingShift || 0) - 4;
  const st = team.style || {};
  const n = (k) => (WP.hash(team.code + name + k) - 0.5) * 16;
  const s = star ? 5 : 0;
  const a = {
    spd: base + n('s') + (st.spd || 0),
    sht: base + n('h') + s + (st.shot || 0),
    acc: base + n('a') + s * 0.8,
    pas: base + n('p') + (st.pas || 0) + s * 0.5,
    def: base + n('d') + (st.def || 0),
    str: base + n('t') + (st.str || 0),
    sta: base + n('m') + (st.spd || 0) * 0.5,
    gk: base + n('g') + s,
  };
  if (p[5]) { a.str += (p[5] - 190) * 0.6; a.spd -= Math.max(0, p[5] - 195) * 0.25; }
  if (role === 'CF') { a.str += 10; a.spd -= 6; a.sht += 1; a.sta -= 3; }
  if (role === 'CB') { a.def += 7; a.str += 8; a.spd -= 3; }
  if (role === 'W') { a.spd += 6; a.sht += 2; a.str -= 5; a.def -= 2; a.sta += 4; }
  if (role === 'D') { a.pas += 3; a.acc += 2; }
  if (role === 'GK') { a.spd -= 15; a.sht -= 20; }
  for (const k in a) a[k] = Math.max(40, Math.min(99, Math.round(a[k])));
  // Точный рейтинг: сдвигаем все параметры, затем добиваем остаток самым весомым для амплуа
  if (team.fixedOvr) {
    const target = Math.max(45, Math.min(97, team.fixedOvr + (ratingShift || 0)));
    const cl = (v) => Math.max(40, Math.min(99, Math.round(v)));
    for (let i = 0; i < 4; i++) { const d = target - WP.ovr(role, a); if (!d) break; for (const k in a) a[k] = cl(a[k] + d); }
    const w = WP.OVR_W[role] || WP.OVR_W.D, keys = Object.keys(w).sort((x, y) => w[y] - w[x]);
    for (let i = 0; i < 24; i++) { const d = target - WP.ovr(role, a); if (!d) break; const k = keys[i % keys.length]; a[k] = cl(a[k] + Math.sign(d)); }
  }
  return a;
};

